/// Central Letterhead Report Engine for official society PDFs — Flutter port of
/// `src/lib/letterheadReportEngine.ts` + the drawing side of `src/lib/pdfLetterhead.ts`.
///
/// Resolution order (never cross-society):
///   Current Society → Society Letterhead → Society Report Settings → Generate PDF
///
/// Official letterhead mode draws the uploaded stationery as a full-page background
/// on every page and keeps report content inside the safe content area. Auto mode
/// draws the digital band (name · address · contact + indigo rule, footer rule +
/// name + page n/N). Plain mode uses standard margins and only stamps page numbers.
///
/// Usage (any module):
/// ```dart
/// final ctx = await resolveLetterheadReportContext(societyId);
/// final report = SocietyReportPdf(letterhead: ctx?.letterhead ?? societyName, mode: ctx?.mode ?? ReportPdfMode.letterhead);
/// report.header(ReportMeta(title: 'Audit report', society: societyName, period: 'Jul 2026'));
/// report.add(SocietyPdf.text('Body…'));
/// report.add(SocietyPdf.table(headers: ['A', 'B'], rows: [['1', '2']]));
/// report.signatures();
/// final bytes = await report.save();
/// ```
