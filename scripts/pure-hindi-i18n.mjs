function transformHi(s) {
  let out = s;
  for (const [a, b] of pairs) {
    if (a === b) continue;
    out = out.split(a).join(b);
  }
  out = out.replace(/प्रवेश प्रवेश/g, 'प्रवेश');
  out = out.replace(/मार्गदर्शन मार्गदर्शन/g, 'मार्गदर्शन');
  out = out.replace(/आगंतुक आगंतुक/g, 'आगंतुक');
  out = out.replace(/निर्धारित निर्धारित/g, 'निर्धारित');
  out = out.replace(/उभरता संदेश श्रृंखला/g, 'उभरती संदेश श्रृंखला');
  out = out.replace(/सूचनापट सूचनापट/g, 'सूचनापट');
  return out;
}

let result = '';
let i = 0;
while (i < src.length) {
  if (src.startsWith("hi: '", i)) {
    result += "hi: '";
    i += 5;
    let content = '';
    while (i < src.length) {
      if (src[i] === '\\') {
        content += src[i] + (src[i + 1] || '');
        i += 2;
        continue;
      }
      if (src[i] === "'") break;
      content += src[i];
      i += 1;
    }
    result += transformHi(content);
    if (i < src.length) {
      result += src[i];
      i += 1;
    }
    continue;
  }
  result += src[i];
  i += 1;
}

fs.writeFileSync(path, result);
console.log(`Updated ${path} (${src.length} → ${result.length} chars)`);
